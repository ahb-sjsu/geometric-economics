#!/usr/bin/env python3
"""End-to-end rehearsal of the pilot chain on DECLARED SIMULATED responses.

**This is not a pilot and produces no scale the study may use.** It exists to
prove the chain runs before sixty people are asked to sit through it, which is
the only part of "run the pilot" that can be done without participants.

    stimuli.json -> responses (simulated, declared)
                 -> pilot_analysis -> rehearsal_scale_arm_A.json
                 -> grade_transition, which must REFUSE the simulated scale

The last step is the point. A rehearsal that ended with a usable scale would be
the failure mode the provenance guard exists to prevent.

    python rehearse_chain.py
"""
from __future__ import annotations

import json
import os
import subprocess
import sys

import pilot_analysis as P

HERE = os.path.dirname(os.path.abspath(__file__))


def _one_line(exc, n=150):
    """The guard's own words. Truncating at the first full stop used to work,
    until the scale filenames gained dots and the reason vanished behind them."""
    t = " ".join(str(exc).split())
    return t if len(t) <= n else t[:n - 3] + "..."


def main():
    print("=" * 74)
    print("REHEARSAL OF THE PILOT CHAIN, ON SIMULATED RESPONSES")
    print("=" * 74)

    with open(os.path.join(HERE, "stimuli.json"), encoding="utf-8") as fh:
        stim = json.load(fh)
    print("  stimulus set: %d families on %d shapes"
          % (stim["n_families"], stim["n_distinct_shapes"]))

    recs = P.simulate(n_fam=30, n_part=60, fam_per_part=3, mean_excess=0.45,
                      sd_fam=0.30, sd_part=0.40, sd_res=0.50, seed=2026)
    doc = {"source": "simulated", "arm": "A",
           "note": "rehearsal only, generated by rehearse_chain.py",
           "records": recs}
    path = os.path.join(HERE, "rehearsal_responses.json")
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(doc, fh)
    print("  simulated %d price lists from 60 participants on 30 families"
          % len(recs))

    r = subprocess.run([sys.executable, os.path.join(HERE, "pilot_analysis.py"),
                        path], capture_output=True, text=True)
    tail = [l for l in r.stdout.splitlines() if l.strip()][-6:]
    print()
    print("  pilot_analysis says:")
    for l in tail:
        print("    " + l)

    print()
    print("  does the grader accept the simulated scale?")
    import importlib
    import shutil
    g = importlib.import_module("grade_transition")

    # A missing file would be refused for the wrong reason, which proves
    # nothing about the provenance guard. So the simulated scale is put
    # exactly where the grader looks, and removed again whatever happens.
    real = os.path.join(HERE, "pilot_scale_arm_A.json")
    reh = os.path.join(HERE, "rehearsal_scale_arm_A.json")
    assert not os.path.exists(real), (
        "%s already exists. Refusing to overwrite a real scale for a rehearsal."
        % os.path.basename(real))
    ok = False
    try:
        shutil.copyfile(reh, real)
        print("    simulated scale placed at %s" % os.path.basename(real))
        try:
            g.pilot_sigma("A")
            print("    IT WAS ACCEPTED. THE GUARD IS BROKEN.")
        except AssertionError as e:
            print("    refused on provenance: %s" % _one_line(e))
            ok = True
        except FileNotFoundError:
            print("    refused for the WRONG REASON, file not found")
    finally:
        if os.path.exists(real):
            os.remove(real)
            print("    %s removed, the tree is left clean"
                  % os.path.basename(real))
    if not ok:
        return 1

    # THE ARMS DO NOT SHARE A UNIT, so the grader must also refuse a scale that
    # belongs to the other arm. Reading arm A's file as arm B's is how a study
    # gets barred with the wrong noise, and it would otherwise look like an
    # ordinary successful read.
    print()
    print("  does the grader accept one arm's scale as the other's?")
    doctored = os.path.join(HERE, "pilot_scale_arm_B.json")
    assert not os.path.exists(doctored), (
        "%s already exists. Refusing to overwrite a real scale for a rehearsal."
        % os.path.basename(doctored))
    cross = False
    try:
        with open(reh, encoding="utf-8") as fh:
            d = json.load(fh)
        d["provenance"] = "human"          # clear the provenance guard on purpose
        with open(doctored, "w", encoding="utf-8") as fh:
            json.dump(d, fh)
        print("    arm A's scale, marked human, placed at %s"
              % os.path.basename(doctored))
        try:
            g.pilot_sigma("B")
            print("    IT WAS ACCEPTED. ARM B WOULD BE BARRED WITH ARM A's NOISE.")
        except AssertionError as e:
            print("    refused on arm: %s" % _one_line(e))
            cross = True
    finally:
        if os.path.exists(doctored):
            os.remove(doctored)
            print("    %s removed, the tree is left clean"
                  % os.path.basename(doctored))
    if not cross:
        return 1

    print()
    print("  chain runs, and ends where it should, with no usable scale.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
